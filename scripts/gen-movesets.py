#!/usr/bin/env python3
"""Writes docs/MOVESETS.md, the master list of every species and every move it can learn (issue 299).

Run from the repository root, after gen-species.py and gen-moves.py:

    python3 scripts/gen-movesets.py          write docs/MOVESETS.md
    python3 scripts/gen-movesets.py --check  exit 1 when docs/MOVESETS.md is out of date, change nothing

It reads only moves.json and species.json from src/main/resources, so it needs no network, no new dependencies and
its output is the same on every run. the checkMovesets task runs --check in ./gradlew build, so the file cannot drift from
the game data: after changing the move pools or the species, regenerate the file and commit it. The file is a
reference for balance review and for checking move pools by hand; the game never shows it.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "..", "src", "main", "resources", "com", "oveduumnakal", "gielinorgo")
OUT = os.path.join(HERE, "..", "docs", "MOVESETS.md")


def load(name):
    with open(os.path.join(DATA, name), encoding="utf-8") as handle:
        return json.load(handle)


def species_key(name):
    return name.replace("\u00a0", " ").strip().lower()


def number(value):
    return ("%.2f" % value).rstrip("0").rstrip(".")


def effect_text(move):
    effect = move.get("effect")
    if not effect:
        return ""
    return "%s %d%%" % (effect["status"].title(), round(effect["chance"] * 100))


def notes_text(move):
    notes = []
    if move.get("slot") == "SECOND":
        notes.append("breath")
    if move.get("icy"):
        notes.append("icy")
    return ", ".join(notes)


def render():
    moves = load("moves.json")
    species = load("species.json")
    by_id = {move["id"]: move for move in moves["moves"]}
    lines = [
        "# Movesets",
        "",
        "Generated by `scripts/gen-movesets.py` from `moves.json` and `species.json`. Do not edit by hand:",
        "run `python3 scripts/gen-movesets.py` from the repository root after changing the data. The build fails",
        "when this file is out of date. A creature knows at most 4 moves, the newest 4 it has unlocked.",
        "",
        "## Moves",
        "",
        "| Move | Style | Power | Accuracy | Status | Notes |",
        "|---|---|---|---|---|---|",
    ]
    for move in sorted(moves["moves"], key=lambda m: m["id"]):
        lines.append("| %s | %s | %s | %s | %s | %s |" % (move["name"], move["style"], number(move["power"]),
                     number(move["accuracy"]), effect_text(move), notes_text(move)))

    lines += ["", "## Species", "", "Each move is followed by the level it is learned at.", "",
              "| Species | Level | Style | Pool | Moves learned |", "|---|---|---|---|---|"]
    for entry in sorted(species, key=lambda s: (s["name"].lower(), s["name"])):
        pool_name = moves["species"].get(species_key(entry["name"])) or moves["defaults"].get(entry["style"])
        pool = moves["pools"].get(pool_name)
        learns = ", ".join("%s %d" % (by_id[move_id]["name"], level) for move_id, level in pool["learns"]) \
            if pool else ""
        lines.append("| %s | %d | %s | %s | %s |" % (entry["name"], entry["level"], entry["style"],
                     pool_name or "", learns))

    return "\n".join(lines) + "\n"


def main():
    text = render()
    if "--check" in sys.argv:
        current = ""
        if os.path.exists(OUT):
            with open(OUT, encoding="utf-8") as handle:
                current = handle.read()
        if current != text:
            print("docs/MOVESETS.md is out of date. Run: python3 scripts/gen-movesets.py")
            return 1
        return 0

    with open(OUT, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
    print("Wrote docs/MOVESETS.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
